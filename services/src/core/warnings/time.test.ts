import { describe, expect, it } from "vitest";
import { parseKstTime } from "./time";

// 시각 변환 검사 (BRD-54 4단계)

describe("parseKstTime", () => {
  it.each([
    ["202610140200", "2026-10-13T17:00:00Z"], // 픽스처 첫 발효 시각, 전날로 넘어감
    ["202610140900", "2026-10-14T00:00:00Z"], // 자정 정각
    ["202610141430", "2026-10-14T05:30:00Z"],
    ["202611010800", "2026-10-31T23:00:00Z"], // 월말로 넘어감
    ["202701010000", "2026-12-31T15:00:00Z"], // 연말로 넘어감
    ["202803010100", "2028-02-29T16:00:00Z"], // 윤년 2월 29일로 넘어감
    ["202802292359", "2028-02-29T14:59:00Z"], // 윤년 2월 29일
  ])("%s (KST) → %s", (raw, iso) => {
    expect(parseKstTime(raw)).toEqual({ kind: "time", iso });
  });

  it.each(["0", ""])("값 없음: %j", (raw) => {
    expect(parseKstTime(raw)).toEqual({ kind: "none" });
  });

  it.each([
    "202613010000", // 13월
    "202600010000", // 0월
    "202610000000", // 0일
    "202602290000", // 평년 2월 29일
    "202604310000", // 4월 31일
    "202610142400", // 24시
    "202610141260", // 60분
    "20261014020", // 11자리
    "2026101402000", // 13자리
    "2026-10-1402", // 숫자 아님
    " 202610140200", // 앞 공백
    "00000101000", // 자리 부족
    "000501010000", // 1900년대로 바뀌는 연도
  ])("잘못된 값: %j", (raw) => {
    expect(parseKstTime(raw)).toEqual({ kind: "invalid", raw });
  });
});
